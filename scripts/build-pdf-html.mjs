// Inlines pdf.js (+ its worker, run on the main thread) and the shared
// extractor into one HTML string so the WebView needs no network or assets.
//
//   npm run build:pdf-html   → src/pdf/extractor-html.ts (generated, ~1.5 MB)
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const read = (p) => readFileSync(require.resolve(p), 'utf8');

const worker = read('pdfjs-dist/legacy/build/pdf.worker.min.js');
const lib = read('pdfjs-dist/legacy/build/pdf.min.js');
const extract = readFileSync(new URL('./pdf-extract.js', import.meta.url), 'utf8');

for (const [name, src] of Object.entries({ worker, lib, extract })) {
  if (/<\/script/i.test(src)) throw new Error(`${name} contains </script and can't be inlined`);
}

// Loading the worker script first defines globalThis.pdfjsWorker, which makes
// pdf.js run its parser on the main thread — no Worker/blob URLs needed.
const bridge = `
(function () {
  var lib = window.pdfjsLib;
  function send(msg) { window.ReactNativeWebView.postMessage(JSON.stringify(msg)); }
  function b64ToBytes(b64) {
    var bin = atob(b64), out = new Uint8Array(bin.length);
    for (var i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
    return out;
  }
  async function onMessage(e) {
    var req;
    try { req = JSON.parse(e.data); } catch (_) { return; }
    if (!req || req.type !== 'extract') return;
    try {
      var result = await window.extractPdfItems(lib, b64ToBytes(req.base64), req.password);
      send(Object.assign({ type: 'result', id: req.id }, result));
    } catch (err) {
      send({ type: 'result', id: req.id, ok: false, error: String((err && err.message) || err) });
    }
  }
  window.addEventListener('message', onMessage);
  document.addEventListener('message', onMessage);
  send({ type: 'ready' });
})();`;

const html = `<!doctype html><html><head><meta charset="utf-8"></head><body>
<script>${worker}</script>
<script>${lib}</script>
<script>${extract}</script>
<script>${bridge}</script>
</body></html>`;

writeFileSync(
  new URL('../src/pdf/extractor-html.ts', import.meta.url),
  `// GENERATED by scripts/build-pdf-html.mjs from pdfjs-dist — do not edit.\nexport default ${JSON.stringify(html)};\n`,
);
console.log(`wrote src/pdf/extractor-html.ts (${(html.length / 1024).toFixed(0)} KB)`);
